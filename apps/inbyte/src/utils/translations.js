/**
 * Helper to normalize string for dictionary lookup
 */
const normalizeKey = (str) => {
    if (!str) return '';
    return String(str)
        .toLowerCase()
        .replace(/[^a-z0-9]/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '');
};

/**
 * Resolves localized dish name
 */
export const getLocalizedDishName = (dishName, lang = 'en') => {
    if (lang !== 'ml' || !dishName) return dishName;

    const norm = normalizeKey(dishName);

    // 1. Check exact dish translation dictionary
    for (const [key, val] of Object.entries(EXACT_DISH_TRANSLATIONS)) {
        if (norm.includes(key) || key.includes(norm)) {
            return val.name;
        }
    }

    // 2. Token-by-token food vocabulary translation
    const tokens = dishName.split(/([ \-&/]+)/);
    let matchedAny = false;
    const translatedTokens = tokens.map(token => {
        const clean = token.toLowerCase().trim();
        if (FOOD_VOCABULARY[clean]) {
            matchedAny = true;
            return FOOD_VOCABULARY[clean];
        }
        return token;
    });

    if (matchedAny) {
        return translatedTokens.join('');
    }

    return dishName;
};

